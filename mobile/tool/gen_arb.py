LOCALES = {'en': 0, 'zh': 1, 'th': 2}


def main():
    out_dir = os.path.join(os.path.dirname(__file__), '..', 'lib', 'l10n')
    os.makedirs(out_dir, exist_ok=True)
    for locale, idx in LOCALES.items():
        arb = {'@@locale': locale}
        for key, row in STRINGS.items():
            arb[key] = row[idx]
            if locale == 'en' and row[3]:
                arb['@' + key] = {'placeholders': {n: {'type': t} for n, t in row[3].items()}}
        with open(os.path.join(out_dir, f'app_{locale}.arb'), 'w', encoding='utf-8') as f:
            json.dump(arb, f, ensure_ascii=False, indent=2)
            f.write('\n')
    print(f'wrote {len(STRINGS)} keys x {len(LOCALES)} locales')


if __name__ == '__main__':
    main()
