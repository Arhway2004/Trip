export function r(key: string, params: Record<string, string | number> = {}) {
  const lang = getLocale()
  const value = labels[key]?.[lang === 'zh' ? 1 : lang === 'th' ? 2 : 0] || key
  return value.replace(/\{(\w+)\}/g, (match, name: string) =>
    String(params[name] ?? match),
  )
}
